package com.basic;

public class Loops {
    public static void main(String[] args) {
        //while loop
        int i=1;
        while(i !=5){
            System.out.println(i);
            i++;
        }
        //for loop
        for(int j=1; j<=10; j++){
            System.out.println(j);
        }
    }
}
